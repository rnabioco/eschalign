#!/usr/bin/env Rscript
# Map bundled MODOMICS tRNA modifications onto a reference panel and write the
# `--mods` sidecar (TOML, one [[site]] per ref/pos; see docs/align.md).
#
#   Rscript scripts/modomics_to_toml.R <panel.fa> "<MODOMICS organism>" <out.toml> [clover_dir]
#
# Needs Biostrings, pwalign, purrr, cli, tibble, rlang, stringr, dplyr. The
# mapping code and the cached MODOMICS data come from the sibling clover repo
# (R/modomics.R, inst/extdata/modomics/); nothing is fetched from the network.
# `pos` is 1-based into the FASTA sequence as given (adapters included), as
# modomics_mods() reports it.
#
# MODOMICS says WHICH modification sits at a position, not what it does to the
# basecaller. Every site therefore gets the same generic, uncurated effect:
# any mismatch, a deletion, and a quality dip. Narrow `expect` per mod by hand
# (or from a curated table) where the signature is known.

args <- commandArgs(trailingOnly = TRUE)
if (length(args) < 3) stop("usage: modomics_to_toml.R panel.fa organism out.toml [clover_dir]")
fa_path <- args[1]; organism <- args[2]; out <- args[3]
clover <- if (length(args) >= 4) args[4] else "../clover"

source(file.path(clover, "R", "modomics.R"))
extdata <- file.path(clover, "inst", "extdata", "modomics")
load_cached_modifications <- function() readRDS(file.path(extdata, "modifications.rds"))
load_cached_sequences <- function(organism) {
  p <- file.path(extdata, paste0(gsub(" ", "_", organism), ".rds"))
  if (file.exists(p)) readRDS(p) else NULL
}

fasta <- Biostrings::readDNAStringSet(fa_path)
mods <- suppressMessages(modomics_mods(fasta, organism))
# Several MODOMICS sequences can map to one reference (isodecoders, variant
# entries), repeating a (ref, pos). The sidecar allows one row per position:
# keep the most frequent modification, preferring named mods over MODOMICS
# placeholders (xG, xX, 1RN...), and list the rest in the row's comment.
key <- paste(mods$ref, mods$pos)
rows <- lapply(split(seq_len(nrow(mods)), key), function(ix) {
  tab <- table(mods$mod1[ix])
  nm <- names(tab)
  best <- nm[order(-as.integer(tab), grepl("^(x|[0-9]R)", nm), nm)][1]
  first <- ix[mods$mod1[ix] == best][1]
  also <- setdiff(unique(mods$mod1[ix]), best)
  out <- mods[first, ]
  out$also <- if (length(also)) paste(also, collapse = ", ") else NA_character_
  out
})
mods <- do.call(rbind, rows)
mods <- mods[order(match(mods$ref, names(fasta)), mods$pos), ]

q <- function(x) paste0('"', gsub('(["\\\\])', "\\\\\\1", x), '"')
lines <- c(
  sprintf("# Generated by scripts/modomics_to_toml.R from MODOMICS (%s) on %s.", organism, format(Sys.Date())),
  sprintf("# Panel: %s. %d sites on %d references.", basename(fa_path), nrow(mods), length(unique(mods$ref))),
  "# pos is 1-based into the FASTA sequence as given (adapters included).",
  "# expect is a generic, uncurated default; MODOMICS does not say what a mod does to the signal.",
  ""
)
for (i in seq_len(nrow(mods))) {
  lines <- c(lines,
    sprintf("# %s%s", mods$mod_full[i], if (is.na(mods$also[i])) "" else paste0(" (also reported: ", mods$also[i], ")")),
    "[[site]]",
    sprintf("ref = %s", q(mods$ref[i])),
    sprintf("pos = %d", as.integer(mods$pos[i])),
    sprintf("mod = %s", q(mods$mod1[i])),
    'expect = ["mismatch:ACGT", "deletion", "qdip"]',
    sprintf("source = %s", q(paste0("modomics:", organism))),
    "")
}
writeLines(lines, out)
message(sprintf("wrote %d sites to %s", nrow(mods), out))
